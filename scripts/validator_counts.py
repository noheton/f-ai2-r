#!/usr/bin/env python3
"""Count the checks of the two validators from their source and write them as LaTeX macros (paper/checks.tex).

The paper's Table of checks gives no typed numbers: the number of checks of a validator, and how many can fail or only
warn, are read from the `print(f"[{'FAIL' if ...}]` / `'WARN' if` lines of its validate command. The package is read
from a checkout whose commit is recorded in the macro \\MChkPkgCommit.

Usage: python3 scripts/validator_counts.py --package ../aiprov/src/aiprov/provlog.py [--out paper/checks.tex]
"""
from __future__ import annotations

import argparse
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent


def counts(path: pathlib.Path) -> tuple[int, int, int]:
    text = path.read_text(encoding="utf-8")
    # the skill line validates in cmd_validate, the package in validate_graph
    start = min(i for i in (text.find("def cmd_validate"), text.find("def validate_graph")) if i != -1)
    end = text.find("\ndef ", start + 1)
    body = text[start:end if end != -1 else None]
    fail = len(re.findall(r"\[\{'FAIL' if", body))
    warn = len(re.findall(r"\[\{'WARN' if", body))
    return fail + warn, fail, warn


def commit(path: pathlib.Path) -> str:
    r = subprocess.run(["git", "-C", str(path.parent), "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=False)
    return r.stdout.strip() or "unknown"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--package", required=True)
    ap.add_argument("--out", default=str(ROOT / "paper" / "checks.tex"))
    a = ap.parse_args()
    pkg = pathlib.Path(a.package)
    sk = counts(ROOT / "scripts" / "provlog.py")
    pk = counts(pkg)
    lines = ["% generated by scripts/validator_counts.py - do not edit",
             f"\\newcommand{{\\MChkSkill}}{{{sk[0]}}}\\newcommand{{\\MChkSkillFail}}{{{sk[1]}}}\\newcommand{{\\MChkSkillWarn}}{{{sk[2]}}}",
             f"\\newcommand{{\\MChkPkg}}{{{pk[0]}}}\\newcommand{{\\MChkPkgFail}}{{{pk[1]}}}\\newcommand{{\\MChkPkgWarn}}{{{pk[2]}}}",
             f"\\newcommand{{\\MChkPkgCommit}}{{{commit(pkg)}}}", ""]
    pathlib.Path(a.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"skill line {sk}, package {pk} (commit {commit(pkg)}) -> {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
